#!/usr/bin/env python3
"""Generate src/vm/SDL2PixelFormats.inc from scripts/sdl2-pixelformats.txt.
Usage: gen-sdl2-pixelformat-table.py <pixelformats.txt> <out.inc>
The data file holds one "SDL_PIXELFORMAT_NAME value" pair per line.
"""
import sys

lines = [l.split() for l in open(sys.argv[1]) if l.strip() and not l.startswith("#")]
out = ["// SDL2PixelFormats.inc - GENERATED by scripts/gen-sdl2-pixelformat-table.py; do not edit.",
       "struct PixelFormatName { const char* name; uint32_t value; };",
       "static const PixelFormatName kPixelFormatNames[] = {"]
out += ['    { "%s", %su },' % (n, v) for n, v in lines]
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
