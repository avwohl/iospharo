#!/usr/bin/env python3
"""Generate scripts/cogdiff/sdl2diff_zero.st: call every SDL2 function with
zero or null arguments through the image FFI and print what each answers.

The script is a differential test.  It runs on stock Cog (real libSDL2) and on
this VM.  Every line is "name -> result | SDL_GetError text".  A pointer result
prints as null or nonnull.

Usage: gen-sdl2diff-zero.py <prototypes.json> <skip.txt> <out.st>
skip.txt lists the functions that must not be called: those that stop the
process, block, or crash real SDL with a null argument.
"""
import json
import re
import sys

protos = json.load(open(sys.argv[1]))
skip = set(l.split("#")[0].strip() for l in open(sys.argv[2]) if l.split("#")[0].strip())

INT_TYPES = {
    "int": "int", "unsigned int": "uint32", "Uint8": "uint8", "Uint16": "uint16", "Uint32": "uint32",
    "Uint64": "uint64", "Sint8": "int8", "Sint16": "int16", "Sint32": "int32", "Sint64": "int64",
    "size_t": "size_t", "long": "long", "unsigned long": "ulong", "SDL_bool": "int", "SDL_threadID": "ulong",
    "SDL_TimerID": "int", "SDL_AudioDeviceID": "uint32", "SDL_AudioFormat": "uint16", "SDL_JoystickID": "int32",
    "SDL_SensorID": "int32", "SDL_TouchID": "int64", "SDL_GestureID": "int64", "SDL_FingerID": "int64",
    "SDL_Keycode": "int32", "SDL_Scancode": "int", "SDL_BlendMode": "uint32", "SDL_TLSID": "uint32",
    "SDL_SpinLock": "int", "SDL_AssertState": "int",
}


def base(t):
    return re.sub(r"\b(const|struct|SDL_OUT_\w+|SDL_IN_\w+|SDL_INOUT_\w+)\b(\([^)]*\))?", "", t).strip()


def ffi_type(t):
    t = base(t)
    if "(" in t or "..." in t:
        return None
    if "*" in t:
        return "void*"
    if t in INT_TYPES:
        return INT_TYPES[t]
    if t in ("float", "double"):
        return t
    if re.match(r"SDL_\w+(Axis|Button|Type|Status|Mode|State|Level|Priority|Orientation|Action|Flip|Format|Event|Cursor|Flags|Hat)$", t):
        return "int"
    if t.startswith("SDL_") and t not in ("SDL_JoystickGUID", "SDL_GUID", "SDL_GameControllerButtonBind"):
        return "int"
    return None


def split_params(p):
    p = p.strip()
    if p in ("void", ""):
        return []
    depth, cur, res = 0, "", []
    for ch in p:
        if ch == "(":
            depth += 1
        if ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            res.append(cur.strip())
            cur = ""
        else:
            cur += ch
    res.append(cur.strip())
    return res


def param_type(decl):
    decl = re.sub(r"\bSDL_(?:IN|OUT|INOUT)_\w+(?:\([^)]*\))?\s*", "", decl)
    if "(" in decl:
        return "void*"
    m = re.match(r"(.*?)(\w+)(\[\d*\])?$", decl)
    if not m or not m.group(1).strip():
        return ffi_type(decl)
    t = m.group(1).strip() + ("*" if m.group(3) else "")
    return ffi_type(t)


methods = []
calls = []
for name in sorted(protos):
    header, ret, params = protos[name]
    if name in skip or not name.startswith("SDL_"):
        continue
    ps = split_params(params)
    ptypes = [param_type(p) for p in ps]
    if any(t is None for t in ptypes) or any("..." in p for p in ps):
        continue
    rbase = base(ret.replace("DECLSPEC", ""))
    if rbase == "void":
        rtype = "void"
    elif "*" in rbase:
        rtype = "void*"
    else:
        rtype = ffi_type(rbase)
    if rtype is None:
        continue
    sel = "z" + name[4:].replace("_", "")
    args = []
    argdecl = []
    for i, t in enumerate(ptypes):
        argdecl.append("%s a%d" % (t, i))
        args.append("nil" if t == "void*" else ("0.0" if t in ("float", "double") else "0"))
    if len(ptypes) == 0:
        selector = sel
        send = "SDL2 %s" % sel
    else:
        selector = "".join("%s: a%d " % (("z" + name[4:].replace("_", "")) if i == 0 else "p", i) for i in range(len(ptypes))).strip()
        send = "SDL2 " + " ".join("%s: %s" % (("z" + name[4:].replace("_", "")) if i == 0 else "p", a) for i, a in enumerate(args))
    methods.append("%s ^ self ffiCall: #( %s %s ( %s ) )" % (selector, rtype, name, ", ".join(argdecl)))
    calls.append((name, rtype, send))

out = []
out.append('"sdl2diff_zero.st -- GENERATED by scripts/gen-sdl2diff-zero.py; do not edit.\n'
           'Every SDL2 function that the image FFI can call is called with zero or null arguments.\n'
           'Each line: name -> result | SDL_GetError text.  A pointer prints as null or nonnull.\n'
           'Run on stock Cog (real libSDL2, SDL_VIDEODRIVER=dummy) and on this VM and compare."')
out.append("| out defs show r err trace |")
out.append("out := WriteStream on: String new.")
out.append("defs := OrderedCollection new.")
for m in methods:
    out.append("defs add: '%s'." % m.replace("'", "''"))
out.append("defs do: [ :d | SDL2 class compile: d classified: 'z' ].")

out.append("SDL2 class compile: 'zInitAll ^ self ffiCall: #( int SDL_Init ( uint32 0x7231 ) )' classified: 'z'.")
out.append("SDL2 class compile: 'zClearErr ^ self ffiCall: #( void SDL_ClearError ( ) )' classified: 'z'.")
out.append("SDL2 class compile: 'zGetErr ^ self ffiCall: #( String SDL_GetError ( ) )' classified: 'z'.")
out.append("SDL2 zInitAll: 16rF230.")
out.append("trace := (FileSystem workingDirectory / 'trace.txt') ensureCreateFile writeStream.")
out.append("show := [ :label :res | out << label << ' -> ' << res << ' | ' << SDL2 zGetErr printString; nextPut: Character lf. trace nextPutAll: '= ', label; nextPut: Character lf; flush ].")
for name, rtype, send in calls:
    if rtype == "void":
        out.append("trace nextPutAll: '> %s'; nextPut: Character lf; flush. SDL2 zClearErr. [ %s. show value: '%s' value: 'void' ] on: Error do: [ :e | show value: '%s' value: 'ERROR ', e class name ]." % (name, send, name, name))
    elif rtype == "void*":
        out.append("trace nextPutAll: '> %s'; nextPut: Character lf; flush. SDL2 zClearErr. [ r := %s. show value: '%s' value: ((r isNil or: [ r isNull ]) ifTrue: [ 'null' ] ifFalse: [ 'nonnull' ]) ] on: Error do: [ :e | show value: '%s' value: 'ERROR ', e class name ]." % (name, send, name, name))
    else:
        out.append("trace nextPutAll: '> %s'; nextPut: Character lf; flush. SDL2 zClearErr. [ r := %s. show value: '%s' value: r printString ] on: Error do: [ :e | show value: '%s' value: 'ERROR ', e class name ]." % (name, send, name, name))
out.append("out contents")
text = "\n".join(out)
text = text.replace("uint32 0x7231", "uint32 f").replace("zInitAll ^", "zInitAll: f ^")
open(sys.argv[3], "w").write(text + "\n")
sys.stderr.write("%d functions\n" % len(calls))
