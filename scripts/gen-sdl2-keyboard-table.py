#!/usr/bin/env python3
"""Generate src/vm/SDL2KeyTable.inc from scripts/sdl2-keyboard-table.txt.

The data file lists, for each of the 512 SDL scancodes, the scancode name and
the key code of the default US key map, as a real libSDL2 answers them.
Usage: gen-sdl2-keyboard-table.py <table.txt> <out.inc>
"""
import sys

names = [None] * 512
keys = [0] * 512
import re

for line in open(sys.argv[1]):
    m = re.match(r"^(\d+)\|(.*?)\|(-?\d+)\|(.*)$", line.rstrip("\n"))
    names[int(m.group(1))] = m.group(2)
    keys[int(m.group(1))] = int(m.group(3))

out = ["// SDL2KeyTable.inc - GENERATED by scripts/gen-sdl2-keyboard-table.py; do not edit.",
       "// Scancode names and the default key map of SDL2 (512 scancodes).", "",
       "static const char* const kScancodeNames[512] = {"]
for i in range(0, 512, 4):
    out.append("    " + ", ".join('"%s"' % n.replace("\\", "\\\\").replace('"', '\\"') if n else "nullptr" for n in names[i:i + 4]) + ",")
out.append("};")
out.append("")
out.append("static const int32_t kDefaultKeymap[512] = {")
for i in range(0, 512, 8):
    out.append("    " + ", ".join(str(k) for k in keys[i:i + 8]) + ",")
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
