#!/usr/bin/env python3
"""gen-image-fixes.py -- build scripts/pharo-image-fixes.st from scripts/image-fixes/.

scripts/image-fixes/00-header.st holds the helper blocks (fix, add).  Each
other *.st file there holds entries only.  The output has one chunk for each
entries file: the header, then the entries.  A chunk ends with '!', so each
file compiles as its own method, and a defect in one file does not stop the
other files.  A '!' inside an entries file is doubled, as the chunk format
requires.

    python3 scripts/gen-image-fixes.py            write the output file
    python3 scripts/gen-image-fixes.py --check    exit 1 if the output file is stale
    python3 scripts/gen-image-fixes.py --one <entries.st> <out.st>
        write one chunk: the header and the entries of one file (the fixes of
        one package, scripts/pkg-jit-test/fixes/<label>.st)
"""
import glob, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src_dir = os.path.join(here, 'image-fixes')
out_path = os.path.join(here, 'pharo-image-fixes.st')

def chunk_text(text):
    return text.replace('!', '!!')

def check_entries(name, body):
    """Stop for a defect of an entries file that the image would report only
    at file-in time, after a load of some minutes.

    An entries file is the second part of one chunk (one method body).  The
    declarations of that body are in the header.  A line of temporaries in the
    entries file ('| helper |' between two entries) is a syntax error of the
    whole chunk, and no entry of the file runs.  Also: a string or a comment
    that does not end."""
    in_string = in_comment = False
    depth = 0
    line = 1
    start_line = 1
    i = 0
    n = len(body)
    while i < n:
        c = body[i]
        if c == '\n':
            line += 1
        if in_string:
            if c == "'":
                if i + 1 < n and body[i + 1] == "'":
                    i += 1
                else:
                    in_string = False
        elif in_comment:
            if c == '"':
                in_comment = False
        elif c == "'":
            in_string = True
            start_line = line
        elif c == '"':
            in_comment = True
            start_line = line
        elif c == '$':
            i += 1                      # a character literal: skip the character
        elif c in '[({':
            depth += 1
        elif c in '])}':
            depth -= 1
        elif c == '|' and depth == 0:
            sys.exit('%s line %d: temporaries in the middle of the file.  The file is one '
                     'chunk with the declarations of the header (fix, add, resolve).  Keep a '
                     'helper block in a global for the time of the file-in, or inside a block.'
                     % (os.path.basename(name), line))
        i += 1
    if in_string:
        sys.exit('%s: the string that starts at line %d does not end' % (os.path.basename(name), start_line))
    if in_comment:
        sys.exit('%s: the comment that starts at line %d does not end' % (os.path.basename(name), start_line))
    if depth != 0:
        sys.exit('%s: brackets do not balance (depth %d at the end)' % (os.path.basename(name), depth))

def build():
    header = open(os.path.join(src_dir, '00-header.st'), encoding='utf-8').read()
    parts = ['"pharo-image-fixes.st -- GENERATED by scripts/gen-image-fixes.py from\n'
             'scripts/image-fixes/*.st.  Do not edit this file: edit the source files and run\n'
             'the generator.\n\n'
             'Fixes for defects in the Pharo 13 and Pharo 14 images and their tests.  File\n'
             'this in when an image is prepared for a test run (after setup_fake_gui.st), on\n'
             'our VM and on stock Cog.  Every entry has a guard on the defect in the current\n'
             'source, so the file is correct for the two Pharo versions and for an image\n'
             'where upstream repaired the defect.  Each entry prints one line: FIXED, ADDED\n'
             'or SKIP with the reason.  The list of defects is in docs/image_issues.md."!\n']
    names = sorted(n for n in glob.glob(os.path.join(src_dir, '*.st'))
                   if os.path.basename(n) != '00-header.st')
    for name in names:
        body = open(name, encoding='utf-8').read().rstrip() + '\n'
        if '| fix add resolve |' in body:
            sys.exit(os.path.basename(name) + ': an entries file must not hold the header '
                     '(found the declaration of fix, add and resolve)')
        check_entries(name, body)
        parts.append('\n"=== ' + os.path.basename(name) + ' ==="\n'
                     + chunk_text(header.rstrip() + '\n\n' + body) + '!\n')
    return ''.join(parts)

def build_one(name):
    header = open(os.path.join(src_dir, '00-header.st'), encoding='utf-8').read()
    body = open(name, encoding='utf-8').read().rstrip() + '\n'
    if '| fix add resolve |' in body:
        sys.exit(os.path.basename(name) + ': an entries file must not hold the header')
    check_entries(name, body)
    return ('"=== ' + os.path.basename(name) + ' ==="\n'
            + chunk_text(header.rstrip() + '\n\n' + body) + '!\n')

def main():
    args = sys.argv[1:]
    if args[:1] == ['--one']:
        if len(args) != 3:
            sys.exit('usage: gen-image-fixes.py --one <entries.st> <out.st>')
        open(args[2], 'w', encoding='utf-8').write(build_one(args[1]))
        return 0
    text = build()
    if '--check' in sys.argv[1:]:
        current = open(out_path, encoding='utf-8').read() if os.path.exists(out_path) else ''
        if current != text:
            print('scripts/pharo-image-fixes.st is stale: run scripts/gen-image-fixes.py', file=sys.stderr)
            return 1
        return 0
    open(out_path, 'w', encoding='utf-8').write(text)
    print('wrote', out_path)
    return 0

if __name__ == '__main__':
    sys.exit(main())
