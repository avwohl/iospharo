#!/usr/bin/env python3
"""Generate src/vm/SDL2StubsDevices.inc from scripts/sdl2-device-semantics.txt.

The data file holds the answers of a real libSDL2 to each function of the
joystick, game controller, haptic, sensor, touch, gesture, HID and audio
families when no device is present.  This script writes one C++ stub per
function: it sets the error text of the answer and returns its value.

Functions whose answer depends on their arguments, or that do real work
(GUID text, mapping strings, touch ids, audio conversion), are written by
hand in SDL2StubsDeviceHand.inc and are listed in HAND below.

Usage: gen-sdl2-device-stubs.py <allfuncs.json> <semantics.txt> <out.inc>
allfuncs.json is the list of SDL function prototypes read from the SDL2
headers: {name: [header, return type, parameter text]}.
"""
import json
import re
import sys

HAND = {
    "SDL_JoystickGetGUIDString", "SDL_JoystickGetGUIDFromString", "SDL_GetJoystickGUIDInfo",
    "SDL_GameControllerGetStringForAxis", "SDL_GameControllerGetStringForButton",
    "SDL_GameControllerGetAxisFromString", "SDL_GameControllerGetButtonFromString",
    "SDL_GameControllerEventState", "SDL_GameControllerNumMappings", "SDL_GameControllerMappingForIndex",
    "SDL_GameControllerAddMapping", "SDL_GameControllerAddMappingsFromRW", "SDL_GameControllerMappingForGUID",
    "SDL_GetNumTouchDevices", "SDL_GetTouchDevice", "SDL_GetTouchName", "SDL_GetTouchDeviceType",
    "SDL_GetNumTouchFingers", "SDL_GetTouchFinger",
    "SDL_AudioInit", "SDL_AudioQuit", "SDL_OpenAudioDevice", "SDL_GetNumAudioDevices", "SDL_GetAudioDeviceName",
    "SDL_NumJoysticks", "SDL_JoystickEventState", "SDL_JoystickUpdate", "SDL_LockJoysticks", "SDL_UnlockJoysticks",
    "SDL_LockSensors", "SDL_UnlockSensors", "SDL_SensorUpdate", "SDL_GameControllerUpdate", "SDL_NumHaptics", "SDL_NumSensors", "SDL_GetNumAudioDrivers", "SDL_GetAudioDriver", "SDL_GetCurrentAudioDriver",
    "SDL_OpenAudio", "SDL_BuildAudioCVT", "SDL_ConvertAudio", "SDL_NewAudioStream", "SDL_AudioStreamPut",
    "SDL_AudioStreamGet", "SDL_AudioStreamAvailable", "SDL_AudioStreamFlush", "SDL_AudioStreamClear",
    "SDL_FreeAudioStream", "SDL_MixAudio", "SDL_MixAudioFormat", "SDL_LoadWAV_RW", "SDL_FreeWAV",
    "SDL_hid_exit", "SDL_hid_init", "SDL_hid_device_change_count", "SDL_hid_free_enumeration", "SDL_hid_ble_scan",
}
FAMILY = ("SDL_joystick.h", "SDL_gamecontroller.h", "SDL_haptic.h", "SDL_sensor.h", "SDL_touch.h",
          "SDL_hidapi.h", "SDL_gesture.h", "SDL_audio.h")

INTS = {"int": "int", "SDL_bool": "int", "unsigned int": "unsigned", "Uint8": "uint8_t", "Uint16": "uint16_t",
        "Uint32": "uint32_t", "Sint16": "int16_t", "SDL_AudioDeviceID": "uint32_t", "SDL_AudioStatus": "int",
        "SDL_GameControllerAxis": "int", "SDL_GameControllerButton": "int", "SDL_GameControllerType": "int",
        "SDL_JoystickID": "int32_t", "SDL_JoystickPowerLevel": "int", "SDL_JoystickType": "int",
        "SDL_SensorID": "int32_t", "SDL_SensorType": "int", "SDL_TouchDeviceType": "int", "SDL_TouchID": "int64_t"}


def cret(t):
    t = t.strip()
    if "*" in t:
        return "void*"
    if t == "void":
        return "void"
    if t == "float":
        return "float"
    if t == "SDL_JoystickGUID":
        return "sdl2::base::Guid"
    if t == "SDL_GameControllerButtonBind":
        return "DeviceButtonBind"
    return INTS[t]


def literal(ret, result):
    if ret == "void":
        return None
    if ret == "void*":
        return "nullptr"
    if ret == "sdl2::base::Guid":
        return "sdl2::base::Guid{}"
    if ret == "DeviceButtonBind":
        return "DeviceButtonBind{}"
    if ret == "float":
        return repr(float(result)) + "f" if result != "0" else "0.0f"
    return "static_cast<%s>(%s)" % (ret, result)


def main():
    funcs = json.load(open(sys.argv[1]))
    rows = {}
    for line in open(sys.argv[2]):
        if line.startswith("#") or not line.strip():
            continue
        name, result, err = (line.rstrip("\n").split("|", 2) + [""])[:3]
        rows[name] = (result, err)
    out = []
    out.append("// SDL2StubsDevices.inc - GENERATED by scripts/gen-sdl2-device-stubs.py from")
    out.append("// scripts/sdl2-device-semantics.txt.  Do not edit; change the data file or the script.")
    out.append("//")
    out.append("// Joystick, game controller, haptic, sensor, touch, gesture, HID and audio calls")
    out.append("// when no device exists.  Each stub sets the error text of the real answer and")
    out.append("// returns its value.  The arguments are not read: with no device every handle is")
    out.append("// invalid, and every index is out of range.")
    out.append("")
    out.append("struct DeviceButtonBind { int bindType; int a; int b; };   // SDL_GameControllerButtonBind")
    out.append("")
    regs = []
    for name in sorted(rows):
        if name in HAND or name not in funcs or funcs[name][0] not in FAMILY:
            continue
        result, err = rows[name]
        ret = cret(funcs[name][1])
        if result == "ptr:nonnull" or result.startswith("struct:") and ret != "sdl2::base::Guid" and ret != "DeviceButtonBind":
            sys.stderr.write("hand-write needed: %s -> %s\n" % (name, result))
            continue
        if result.startswith("struct:"):
            val = "%s{}" % ret
        elif ret == "void":
            val = None
        else:
            val = literal(ret, result)
        body = []
        if err:
            body.append('sdl2::sys::setError("%s");' % err.replace("\\", "\\\\").replace('"', '\\"'))
        else:
            body.append("sdl2::sys::lastError().clear();" if False else "")
        stmt = " ".join(b for b in body if b)
        short = name
        if val is None:
            out.append("static void stub_%s() { %s }" % (short, stmt))
        else:
            out.append("static %s stub_%s() { %s return %s; }" % (ret, short, stmt, val))
        regs.append(name)
    out.append("")
    out.append("static void registerSDL2DeviceStubs() {")
    for name in regs:
        out.append('    registerFunction("%s", reinterpret_cast<void*>(stub_%s));' % (name, name))
    out.append("}")
    open(sys.argv[3], "w").write("\n".join(out) + "\n")
    sys.stderr.write("generated %d stubs\n" % len(regs))


if __name__ == "__main__":
    main()
