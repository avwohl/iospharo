#!/bin/bash
#
# stage-pr.sh -- copy the Tonel files that a pull request branch changes, so
# that load-pr.st can put the change into a Pharo image.
#
#   scripts/upstream-pr/stage-pr.sh <worktree> <base-ref> <stage-dir>
#
# <worktree>   a checkout of the PR branch (a clone of pharo-project/pharo,
#              pharo-spec/Spec, ...)
# <base-ref>   the branch that the PR goes to, e.g. origin/Pharo15
# <stage-dir>  made new; gets:
#                files.txt      one line per changed .st file: <status> TAB <path>
#                base/<path>    the file at the merge base (no file for an added file)
#                pr/<path>      the file at the head of the branch (no file for a deleted file)
#                load.st        file this into the image (vmrun.sh prep ... load.st)
#
# load.st loads only the definitions that differ between base/ and pr/, so the
# other changes of the branch base since the build of the image do not go in.
set -eu
wt=${1:?usage: stage-pr.sh <worktree> <base-ref> <stage-dir>}
base=${2:?base ref}
out=${3:?stage dir}
REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)

mb=$(git -C "$wt" merge-base "$base" HEAD)
rm -rf "$out"
mkdir -p "$out/base" "$out/pr"
out=$(cd "$out" && pwd)
: > "$out/files.txt"
git -C "$wt" diff --name-status --no-renames "$mb" HEAD -- '*.st' |
while IFS=$'\t' read -r status path; do
    printf '%s\t%s\n' "$status" "$path" >> "$out/files.txt"
    if [ "$status" != A ]; then
        mkdir -p "$out/base/$(dirname "$path")"
        git -C "$wt" show "$mb:$path" > "$out/base/$path"
    fi
    if [ "$status" != D ]; then
        mkdir -p "$out/pr/$(dirname "$path")"
        git -C "$wt" show "HEAD:$path" > "$out/pr/$path"
    fi
done
[ -s "$out/files.txt" ] || { echo "stage-pr: no .st file changed between $mb and HEAD" >&2; exit 1; }

cat > "$out/load.st" <<EOF
"Generated by scripts/upstream-pr/stage-pr.sh for $(git -C "$wt" rev-parse --abbrev-ref HEAD) at $(git -C "$wt" rev-parse --short HEAD) (base $(git -C "$wt" rev-parse --short "$mb"))."
Smalltalk globals at: #UpstreamPrStageDir put: '$out'.
'$REPO/scripts/upstream-pr/load-pr.st' asFileReference fileIn.
Smalltalk globals removeKey: #UpstreamPrStageDir ifAbsent: [ ].
EOF
cat "$out/files.txt"
echo "stage-pr: $out/load.st"
